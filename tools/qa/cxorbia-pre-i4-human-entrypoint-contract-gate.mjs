#!/usr/bin/env node
import fs from 'node:fs';
const read=p=>fs.readFileSync(p,'utf8');
const json=p=>JSON.parse(read(p));
const fail=[]; const ok=(c,m)=>{if(!c)fail.push(m);};
const fb=json('firebase.json');
const dev=read('app/index-backend-dev.html');
const idx=read('app/index.html');
const cfg=read('app/core/config.js');
const ds=read('app/core/data-source.js');
const app=read('app/app.js');
const tenant=read('app/config/runtime.js');
const source=json('backend/config/tya-tenant-runtime-profile.source-safe.json');
const wildcard=fb.hosting?.rewrites?.find(x=>x.source==='**');
ok(wildcard?.destination==='/index-backend-dev.html','DEV_WILDCARD_NOT_CANONICAL_ENTRYPOINT');
ok(dev.includes('config/runtime.js'),'DEV_TENANT_RUNTIME_CONFIG_NOT_LOADED');
ok(idx.includes('config/runtime.js'),'INDEX_TENANT_RUNTIME_CONFIG_NOT_LOADED');
ok(!dev.includes('<script src="core/backend-preview-status.js"></script>'),'DEBUG_STATUS_STATICALLY_LOADED');
ok(dev.includes("p.get('cxAuditUi')==='1'"),'DEBUG_STATUS_NOT_EXPLICITLY_GATED');
ok(!idx.includes('<script src="core/dev-scenario-lab.js"></script>'),'SCENARIO_LAB_STATICALLY_LOADED');
ok(idx.includes("p.get('cxDevLab')!=='1'"),'SCENARIO_LAB_NOT_EXPLICITLY_GATED');
ok(ds.includes("lane==='authenticated-human-canonical'"),'CANONICAL_HUMAN_SOURCE_OWNER_MISSING');
ok(ds.includes("authenticated-human-canonical:awaiting-provider"),'CANONICAL_HUMAN_LOADING_STATE_MISSING');
ok(cfg.includes('CX.applyTenantRuntimeConfig'),'TENANT_BRANDING_AUTHORITY_MISSING');
ok(cfg.includes('localStorage is never branding truth'),'LOCAL_BRANDING_TRUTH_GUARD_MISSING');
ok(!app.includes('Gravicentra<em>CX</em>')&&!app.includes('Powered by Gravicentra CX'),'PREMATURE_GRAVICENTRA_BRAND_VISIBLE');
ok(tenant.includes(source.branding.logoUrl),'TENANT_LOGO_RUNTIME_SOURCE_DESYNC');
ok(source.branding.logoAuthority==='tenant_runtime_config'&&source.branding.localStorageTruth===false,'TENANT_LOGO_AUTHORITY_INVALID');
ok(/^https:\/\//.test(source.branding.logoUrl||''),'TENANT_LOGO_URL_MISSING');
const decision=fail.length?'FAIL_PRE_I4_HUMAN_ENTRYPOINT_CONTRACT':'PASS_PRE_I4_HUMAN_ENTRYPOINT_CONTRACT';
console.log(JSON.stringify({schemaVersion:'cxorbia.pre-i4-human-entrypoint-contract.v1',decision,failures:fail,production:false,hrWrites:0,authWrites:0,providerWrites:0},null,2));
if(fail.length)process.exit(1);
